//Operadores 
let a, b, c, d, e, f, g, h;
// Operadores Aritméticos
// suma = +
a = 3 + 4;
console.log(a);

// resta = -
b = 10 - 5;
console.log(b);

// multiplicación = *
c = 3 * 4;
console.log(c);

// división = /
d = 10 / 2;
console.log(d);

// módulo = %
e = 10 % 3;
console.log(e);

// Potencia = **
f = 2 ** 3;
console.log(f);

// Incremento = ++
g = 5;
// pre-incremento
++g;
console.log(g);
// post-incremento
g++;
console.log(g);
// Decremento = --
h = 5;
// pre-decremento
--h;
console.log(h);
// post-decremento
h--;
console.log(h);